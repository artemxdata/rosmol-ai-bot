def build_analyzer_user(
    message: str,
    session: Session | None,
    memory: Any | None,
    routing_hint: dict[str, Any] | None = None,
) -> str:
    return "\n".join(
        [
            f"Версия промпта: {get_settings().prompt_version}",
            f"Сообщение: {message}",
            f"Предварительная маршрутизация: {routing_hint or {}}",
            f"Сессия: {session.model_dump_json() if session else '{}'}",
            f"Долгосрочная память: {memory.model_dump_json() if memory else '{}'}",
        ]
    )


def build_semantic_recovery_user(
    message: str,
    analysis: QueryAnalysis,
    *,
    failure_reason: str,
) -> str:
    existing_questions = [
        question.text
        for question in analysis.questions[:6]
        if str(question.text or "").strip()
    ]
    return "\n".join(
        [
            f"Версия промпта: {get_settings().prompt_version}",
            f"Причина повторного поиска: {failure_reason}",
            f"Категория: {analysis.category or 'не определена'}",
            f"Мероприятие: {analysis.forum_normalized or 'не определено'}",
            f"Исходный запрос и допустимый контекст: {message[:1600]}",
            f"Текущая декомпозиция: {existing_questions}",
        ]
    )


def build_generator_user(
    questions: list[Question],
    chunks: list[Chunk],
    session: Session | None,
    params: dict[str, Any] | None = None,
    max_chars: int | None = None,
    response_profile: str | None = None,
    profile_guidance: str | None = None,
    retry_reason: str | None = None,
    rejected_draft: str | None = None,
) -> str:
    sources = []
    for idx, chunk in enumerate(chunks, start=1):
        metadata = _compact_source_metadata(chunk.metadata)
        sources.append(
            f"[src:{chunk.chunk_id}] Источник {idx}\n"
            f"Метаданные: {metadata}\n"
            f"Текст: {chunk.text}"
        )
    return "\n\n".join(
        [
            f"Вопросы: {[question.model_dump() for question in questions]}",
            (
                "Разрешённые source-маркеры (копируй ID без изменений): "
                + ", ".join(f"[src:{chunk.chunk_id}]" for chunk in chunks)
            ),
            (
                _generator_retry_guidance(retry_reason)
                if retry_reason
                else ""
            ),
            (
                "Отклонённый черновик (не копируй его механически; исправь указанную "
                f"ошибку):\n{_bounded_rejected_draft(rejected_draft)}"
                if retry_reason and rejected_draft
                else ""
            ),
            (
                f"Максимальная длина ответа без служебных [src:...] — {max_chars} символов. "
                "Сформулируй ответ заново в этом лимите; не обрезай текст."
                if max_chars
                else ""
            ),
            (
                f"Профиль ответа: {response_profile}. {profile_guidance}"
                if response_profile and profile_guidance
                else ""
            ),
            "Обязательный формат: на один вопрос отвечай коротким цельным текстом; "
            "на несколько вопросов — отдельными пунктами в исходном порядке. "
            "Каждый пункт с фактами должен содержать [src:chunk_id] именно того источника; "
            "не ставь несколько source-маркеров после одного пункта; "
            "для пункта с датой, возрастом, сроком или другим числом используй ровно один "
            "source-маркер и не объединяй в нём условия из разных источников; "
            "если не можешь поставить source marker для пункта, не создавай такой пункт.",
            f"Параметры пользователя: {params or {}}",
            f"Сессия: {session.model_dump() if session else {}}",
            "Источники:",
            "\n\n".join(sources),
        ]
    )


def _bounded_rejected_draft(draft: str, *, max_chars: int = 1200) -> str:
    compact = " ".join(str(draft or "").split())
    if len(compact) <= max_chars:
        return compact
    return compact[:max_chars].rstrip() + "…"


def _generator_retry_guidance(retry_reason: str) -> str:
    reason_guidance = {
        "llm_source_citation_failed": (
            "Скопируй разрешённый source ID буквально и поставь маркер в конце "
            "каждого фактического пункта."
        ),
        "llm_source_fact_binding_failed": (
            "Заново сверь каждый факт с текстом источника. Не меняй плательщика или "
            "ответственное лицо, роль участника, обязательность, разрешение или запрет. "
            "Возраст, смену, дату и срок оставь только в той ветке условия, где они указаны. "
            "Раздели факты разных источников на отдельные пункты и заверши каждый ровно "
            "одним соответствующим source-маркером."
        ),
        "llm_response_profile_failed": (
            "Оставь только аспекты, которые прямо запрошены в вопросах, и убери сведения "
            "из соседних тем источника. Каждый запрошенный аспект сохрани."
        ),
        "llm_response_too_long": (
            "Сократи формулировки до прямого ответа и подтверждённых условий без вступления, "
            "повторов и дополнительных советов. Оставь не более одного короткого пункта "
            "на каждый вопрос."
        ),
        "llm_source_coverage_failed": (
            "Ответь на каждый вопрос отдельным пунктом и используй только тот источник, "
            "который подтверждает этот пункт."
        ),
        "llm_response_contract_failed": (
            "Верни содержательный ответ по подтверждённым данным, без общих фраз о нехватке "
            "источников и без неподтверждённых следующих шагов. Не копируй из источников "
            "больше одной пользовательской ссылки на весь ответ."
        ),
    }
    specific_guidance = reason_guidance.get(retry_reason, "Сформулируй ответ заново.")
    return (
        "ПОВТОРНАЯ ПОПЫТКА: предыдущий черновик отклонён контрактом "
        f"({retry_reason}). {specific_guidance} Обязательно поставь хотя бы один "
        "разрешённый source-маркер; при одном источнике используй именно его. "
        "Не используй номера источников, сокращённые или придуманные ID."
    )


def build_judge_user(response: str, sources: list[Chunk]) -> str:
    return "\n\n".join(
        [
            f"Ответ бота:\n{response}",
            "Источники:",
            "\n\n".join(f"[src:{chunk.chunk_id}] {chunk.text}" for chunk in sources),
        ]
    )


def _compact_source_metadata(metadata: dict[str, Any]) -> dict[str, Any]:
    allowed_keys = (
        "forum_normalized",
        "category",
        "topic",
        "source_type",
        "source_category",
        "intent_name",
        "has_conditional_logic",
        "conditions_summary",
        "dates_mentioned",
        "parent_chunk_id",
        "source_heading_path",
        "linked_section_names",
        "linked_anchor_chunk_id",
    )
    return {
        key: value
        for key in allowed_keys
        if (value := metadata.get(key)) not in (None, "", [], {})
    }
