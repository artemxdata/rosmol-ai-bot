from __future__ import annotations

import re
import tomllib
from pathlib import Path

from packaging.requirements import Requirement

ROOT = Path(__file__).resolve().parents[1]
SHA256_REF = re.compile(r"@sha256:[0-9a-f]{64}(?:\s|$)")


def _read(path: str) -> str:
    return (ROOT / path).read_text(encoding="utf-8")


def _input_requirements(path: str) -> set[str]:
    result: set[str] = set()
    for raw_line in _read(path).splitlines():
        line = raw_line.strip()
        if not line or line.startswith(("#", "-r ")):
            continue
        result.add(str(Requirement(line)))
    return result


def _project_requirements(group: str | None = None) -> set[str]:
    config = tomllib.loads(_read("pyproject.toml"))
    if group is None:
        values = config["project"]["dependencies"]
    else:
        values = config["project"]["optional-dependencies"][group]
    return {str(Requirement(value)) for value in values}


def _assert_hashed_lock(path: str) -> None:
    text = _read(path)
    assert "autogenerated by pip-compile with Python 3.11" in text
    assert "--hash=sha256:" in text
    assert "# WARNING:" not in text

    starts = list(re.finditer(r"(?m)^(?P<name>[A-Za-z0-9_.-]+)==[^\s\\]+", text))
    assert starts, path
    for index, match in enumerate(starts):
        end = starts[index + 1].start() if index + 1 < len(starts) else len(text)
        assert "--hash=sha256:" in text[match.start() : end], match.group("name")


def test_requirement_inputs_are_kept_in_sync_with_pyproject() -> None:
    assert _input_requirements("requirements/runtime.in") == _project_requirements()
    assert _input_requirements("requirements/dev.in") == _project_requirements("dev")
    assert _input_requirements("requirements/ml.in") == _project_requirements("ml") | {
        "torch==2.13.0+cpu"
    }
    assert _input_requirements("requirements/sdist-build-tools.in") == {
        "pip==26.1.2",
        "setuptools==83.0.0",
    }


def test_all_dependency_locks_are_complete_and_hash_pinned() -> None:
    for path in (
        "requirements/lock-tools.lock",
        "requirements/sdist-build-tools.lock",
        "requirements/runtime.lock",
        "requirements/dev.lock",
        "requirements/ml.lock",
    ):
        _assert_hashed_lock(path)

    assert "torch==2.13.0+cpu" in _read("requirements/ml.lock")
    assert "https://download.pytorch.org/whl/cpu" in _read("requirements/ml.lock")


