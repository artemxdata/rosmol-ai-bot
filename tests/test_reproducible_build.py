def test_compose_external_images_are_immutable_linux_amd64_manifests() -> None:
    compose = _read("docker-compose.yml")
    tls = _read("docker-compose.admin-tls.yml")
    production = _read("docker-compose.prod.yml")
    expected = (
        "postgres:16.14-alpine3.24",
        "redis:7.4.9-alpine",
        "qdrant/qdrant:v1.18.3",
        "nginx:1.30.4-alpine",
        "certbot/certbot:v5.7.0",
        "ubuntu/squid:6.6-24.04_edge",
        "haproxy:3.4.2-alpine",
    )
    combined = f"{compose}\n{tls}\n{production}"

    assert combined.count("platform: linux/amd64") >= len(expected)
    for image in expected:
        line = next(line for line in combined.splitlines() if f"image: {image}@" in line)
        assert SHA256_REF.search(line)


